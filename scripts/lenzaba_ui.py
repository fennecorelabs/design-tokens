"""Generate the application reference adapter without changing legacy themes."""
import json
import re


ROOT = '[data-product="lenzaba"][data-ui="reference-v1"]'


def generate_ui(pkg, palette, oklch):
    ui = json.loads((pkg / 'src/lenzaba-ui.json').read_text())
    css = ['''/* Generated by scripts/generate-lenzaba.py. Import after existing theme CSS.
 * Palette: src/lenzaba-palette.json. Application metrics: src/lenzaba-ui.json.
 * Only reference-v1 roots opt in; applications retain ownership of .dark. */
@import "./lenzaba-brand.css";''']

    def block(selectors, roles):
        return selectors + ' {\n' + ''.join(f'  --{k}: {v};\n' for k, v in roles.items()) + '}'

    for mode in ('light', 'dark'):
        scope = ROOT if mode == 'light' else f'{ROOT}.dark, .dark {ROOT}'
        roots = scope.split(', ')
        selectors = ',\n'.join(roots + [f'{root} [data-theme="cold-purple"]' for root in roots])
        colors = palette['themes'][mode] | ui['themes'][mode]
        roles = {f'lenzaba-{re.sub(r"(?<!^)(?=[A-Z])", "-", key).lower()}': oklch(value)
                 for key, value in colors.items()}
        aliases = {
            'background': 'background', 'card': 'surface', 'popover': 'surface',
            'surface': 'surface', 'surface-raised': 'raised', 'muted': 'raised',
            'foreground': 'text', 'card-foreground': 'text', 'popover-foreground': 'text',
            'muted-foreground': 'muted', 'border': 'border',
            'primary': 'action', 'primary-foreground': 'on-action',
            'secondary': 'secondary', 'secondary-foreground': 'on-secondary',
            'accent': 'accent-surface', 'accent-foreground': 'accent', 'ring': 'focus',
            'control-border': 'control-border', 'input': 'control-border',
            'border-strong': 'control-border', 'destructive': 'error',
            'destructive-foreground': 'on-error',
        }
        roles |= {key: f'var(--lenzaba-{value})' for key, value in aliases.items()}
        for family, color in {'success': 'success', 'warning': 'warning', 'error': 'error',
                              'danger': 'error', 'info': 'info', 'attention': 'warning'}.items():
            for suffix in ('', '-foreground', '-border'):
                roles[f'status-{family}{suffix}'] = f'var(--lenzaba-{color})'
            for suffix in ('-surface', '-subtle', '-muted'):
                roles[f'status-{family}{suffix}'] = f'var(--lenzaba-{color}-surface)'
        # Rebind font aliases on shell wrappers, where inherited var() references
        # would otherwise retain the shell's Inter binding.
        roles |= {'font-geist-sans': 'var(--font-lenzaba-body)',
                  'font-sans': 'var(--font-lenzaba-body)',
                  'font-body': 'var(--font-lenzaba-body)',
                  'font-display': 'var(--font-lenzaba-display)',
                  'radius': f"{ui['radius']['card']}px"}
        css.append(block(selectors, roles))

    metrics = {'ui-control-height': f"{ui['density']['comfortable']}px",
               'ui-control-font-size': f"{ui['type']['dense']}px"}
    for family in ('radius', 'type', 'icons'):
        for key, value in ui[family].items():
            name = re.sub(r'(?<!^)(?=[A-Z])', '-', key).lower()
            metrics[f'ui-{family}-{name}'] = str(value) if key == 'stroke' else f'{value}px'
    metrics |= {f'ui-space-{value}': f'{value}px' for value in ui['spacing']}
    metrics['ui-feedback-duration'] = f"{ui['motion']['feedbackMs']}ms"
    css.append(block(f':where({ROOT})', metrics))

    # :where keeps view attributes at equal specificity to root attributes so
    # nested views can choose their own density through ordinary inheritance.
    def attribute_scope(attribute):
        return f':where({ROOT}){attribute},\n:where({ROOT}) {attribute}'

    for density in ('comfortable', 'compact'):
        css.append(block(attribute_scope(f'[data-density="{density}"]'),
                         {'ui-control-height': f"{ui['density'][density]}px"}))
    readable = attribute_scope('[data-readable="true"]')
    readable += f',\n:where({ROOT}[data-readable="true"], {ROOT} [data-readable="true"]) [data-density]'
    css.append(block(readable, {'ui-control-height': f"{ui['density']['readable']}px",
                                'ui-control-font-size': f"{ui['type']['body']}px"}))
    css.append('@media (any-pointer: coarse) {\n' + block(
        ROOT + ',\n' + attribute_scope('[data-density]'),
        {'ui-control-height': f"{ui['density']['touch']}px"}) + '\n}')
    css.append('@media (prefers-reduced-motion: reduce) {\n' + block(
        ROOT, {'ui-feedback-duration': f"{ui['motion']['reducedMotionMs']}ms"}) + '\n}')
    return '\n\n'.join(css) + '\n'
